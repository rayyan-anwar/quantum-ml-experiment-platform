"""Run the full comparison suite and ablation; save genuine results. Usage: python scripts/evaluate.py [--seeds 5]
Author: Rayyan Anwar"""
import argparse
import json
import platform
import sys
import time
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from app.experiments import MODELS, ablation, run_model, run_suite  # noqa: E402
from app.data import load_dataset, split_scale  # noqa: E402


def to_md(r):
    e, s, a = r["environment"], r["suite"], r["ablation"]
    L = ["# Results (generated by `scripts/evaluate.py`)", "",
         f"- Created (UTC): {r['created_utc']}; machine: {e['platform']}; Python {e['python']}; NumPy {e['numpy']}; CPUs {e['cpu_count']}; total {r['total_seconds']:.0f} s",
         f"- Noise-free state-vector simulation. {len(s['seeds'])} seeds per cell (data split, data draw and initialisation change with the seed). "
         f"Baselines and the quantum-kernel SVM use 3-fold CV grids on the training split; the VQC uses its fixed config: {s['vqc_config']}.", "",
         "## Test accuracy, mean ± std over seeds (parameter count in brackets)", "",
         "| Dataset | " + " | ".join(MODELS) + " |", "|---|" + "---:|" * len(MODELS)]
    for ds, row in s["aggregate"].items():
        L.append(f"| {ds} | " + " | ".join(f"{row[m]['test_acc_mean']:.3f} ± {row[m]['test_acc_std']:.3f} ({row[m]['params']})" for m in MODELS) + " |")
    L += ["", f"## VQC ablation on {a['dataset']} (test accuracy, mean ± std over {len(a['seeds'])} seeds)", "", "| Configuration | Parameters | Test accuracy |", "|---|---:|---:|"]
    for k, v in a["results"].items():
        L.append(f"| {k} | {v['params']} | {v['test_acc_mean']:.3f} ± {v['test_acc_std']:.3f} |")
    L += ["", "Parameter counts for SVMs are support-vector counts (not comparable to trainable weights). Differences smaller than about one standard deviation should not be read as real."]
    return "\n".join(L) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--seeds", type=int, default=5)
    n = ap.parse_args().seeds
    import numpy as np
    t0 = time.perf_counter()
    seeds = tuple(range(n))
    r = {"created_utc": datetime.now(timezone.utc).isoformat(timespec="seconds"),
         "environment": {"platform": platform.platform(), "python": sys.version.split()[0], "numpy": np.__version__, "cpu_count": __import__("os").cpu_count()},
         "suite": run_suite(seeds=seeds), "ablation": ablation("moons", seeds=seeds)}
    X, y = load_dataset("moons", 0)
    Xtr, Xte, ytr, yte = split_scale(X, y, 0)
    r["training_curve_moons_seed0"] = {"loss": run_model("vqc", Xtr, ytr, Xte, yte, 0)["loss_curve"]}
    r["total_seconds"] = time.perf_counter() - t0
    (ROOT / "results").mkdir(exist_ok=True)
    (ROOT / "results" / "results.json").write_text(json.dumps(r, indent=2))
    (ROOT / "results" / "RESULTS.md").write_text(to_md(r))
    print(to_md(r))


if __name__ == "__main__":
    main()
